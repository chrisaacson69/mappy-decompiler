#!/usr/bin/env python3
"""
data_pointers.py - the data walk's second level: the blobs reached only through a labelled pointer table.
For each table below (its words and count proven by the code that reads it), every word's target in PRG
gets a provenance name <stem>_<offset>, where offset is the value the reader indexes with (Y or X; 4 per
record for tbl_text_lines). A target shared by several offsets is named once, at the first, and its
`why` lists them all. Targets already labelled are left alone.

  py -3.14 mappy/data_pointers.py          -> print the batch
  py -3.14 mappy/data_pointers.py --write  -> write _scratch/batch_data_pointers.py for apply_names.py
"""
import re
import sys
from pathlib import Path

from code_map import label_names

from paths import ROM, SCRATCH
PRG = ROM.read_bytes()[16:16 + 0x4000]


def word(a):
    return PRG[a - 0xC000] | PRG[a - 0xC000 + 1] << 8


# (table label, base, words, stride, word offset in a record, stem, the reader and its count evidence)
TABLES = [
    ("tbl_bcd_add_records", 0xD536, 7, 2, 0, "bcd_add_record", "bcd_add_from_table; Y up to $0C"),
    ("tbl_bcd_number_entries", 0xD640, 12, 2, 0, "bcd_number_entry", "queue_bcd_number; ends at its first target $D658"),
    ("tbl_vram_packets", 0xD7AD, 10, 2, 0, "vram_packet", "queue_vram_packet; ends at its first target $D7C1"),
    ("tbl_text_lines", 0xCF08, 5, 4, 2, "text_line", "draw_indexed_text_line; Y 0-$10 by 4 (show_bonus_results)"),
    ("tbl_trampoline_set_ptrs", 0xE4F1, 7, 2, 0, "trampoline_set", "load_round_trampolines; tbl_round_trampoline_set holds 0-$0C"),
    ("tbl_trampoline_pictures", 0xE569, 11, 2, 0, "trampoline_picture", "draw_text_from_table; frames 0-9, $14 broken"),
    ("tbl_item_pictures", 0xE7B9, 6, 2, 0, "item_picture", "draw_item (pairs 0-8) and erase_item ($0A)"),
    ("tbl_round_door_lists", 0xEAFC, 16, 2, 0, "round_doors", "load_round_doors by stage_number*2; ends at its first target $EB1C"),
    ("tbl_door_pictures", 0xEC4F, 17, 2, 0, "door_picture", "draw_door_kind_y; ends at its first target $EC71"),
    ("tbl_floor_trap_pictures", 0xF128, 3, 2, 0, "floor_trap_picture", "draw_floor_trap_frame; X 0, 2, 4"),
    ("tbl_bonus_target_pictures", 0xF263, 2, 2, 0, "bonus_target_picture", "animate_bonus_target; frame & $10 >> 3"),
    ("tbl_bonus_target_lists", 0xF27F, 5, 2, 0, "bonus_targets", "load_bonus_targets by is_bonus_round (2-8; 0 has none)"),
    ("tbl_voice_stream_ptrs", 0xF853, 19, 2, 0, "voice_stream", "load_voice_stream_ptr by voice*2, voice 0 skipped (beq); ends at voice13_stream $F879"),
]


def labelled():
    return set(label_names())


def batch():
    have, out, seen = labelled(), [], {}
    for label, base, n, stride, woff, stem, ev in TABLES:
        for k in range(1 if stem == "voice_stream" else 0, n):   # voice 0 is never read
            t = word(base + stride * k + woff)
            off = stride * k
            if t < 0xC000 or t in have:
                continue
            seen.setdefault(t, (label, stem, ev, []))[3].append(off)
    for t, (label, stem, ev, offs) in sorted(seen.items()):
        name = f"{stem}_{offs[0]:02x}"
        why = (f"Data walk 2026-10-26 (pointer level): the target of {label} at offset"
               f"{'s' if len(offs) > 1 else ''} {', '.join(f'${o:02X}' for o in offs)} ({ev}).")
        out.append((f"{t:04X}", name, "data", "HIGH", why))
    return out


def main():
    b = batch()
    for e in b:
        print(f"${e[0]}  {e[1]:28}  {e[4]}")
    print(f"\n{len(b)} blob(s)")
    if "--write" in sys.argv:
        (SCRATCH / "batch_data_pointers.py").write_text(
            "# generated by data_pointers.py\nBATCH = [\n" + "".join(f"    {e!r},\n" for e in b) + "]\n",
            encoding="utf-8")


if __name__ == "__main__":
    main()
